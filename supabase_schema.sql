-- 1. EXTENSIONES
CREATE EXTENSION IF NOT EXISTS "uuid-ossp";

-- 2. TABLA DE PERFILES DE USUARIOS (Vinculada a Supabase Auth)
CREATE TABLE IF NOT EXISTS public.profiles (
  id UUID PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
  email TEXT UNIQUE,
  full_name TEXT,
  phone TEXT,
  role TEXT DEFAULT 'customer' CHECK (role IN ('customer', 'washer', 'cashier', 'admin')),
  avatar_url TEXT,
  created_at TIMESTAMPTZ DEFAULT NOW(),
  updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- 3. TABLA DE SERVICIOS Y TARIFAS
CREATE TABLE IF NOT EXISTS public.services (
  id TEXT PRIMARY KEY,
  name TEXT NOT NULL,
  type TEXT NOT NULL CHECK (type IN ('moto', 'carro', 'suv', 'taxi', 'otro')),
  price NUMERIC(12, 2) NOT NULL DEFAULT 0,
  duration INT NOT NULL DEFAULT 30, -- Minutos estimados
  comm_type TEXT DEFAULT 'porcentaje' CHECK (comm_type IN ('porcentaje', 'fijo')),
  comm_val NUMERIC(10, 2) DEFAULT 40,
  active BOOLEAN DEFAULT TRUE,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 4. TABLA DE LAVADORES / PERSONAL
CREATE TABLE IF NOT EXISTS public.washers (
  id TEXT PRIMARY KEY,
  name TEXT NOT NULL,
  phone TEXT,
  active BOOLEAN DEFAULT TRUE,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 5. TABLA PRINCIPAL DE ÓRDENES / VEHÍCULOS EN PATIO
CREATE TABLE IF NOT EXISTS public.orders (
  id TEXT PRIMARY KEY DEFAULT uuid_generate_v4()::TEXT,
  ticket_number BIGINT GENERATED BY DEFAULT AS IDENTITY,
  plate TEXT NOT NULL,
  vehicle_type TEXT NOT NULL CHECK (vehicle_type IN ('moto', 'carro', 'suv', 'taxi', 'otro')),
  service_id TEXT REFERENCES public.services(id) ON DELETE SET NULL,
  service_name TEXT NOT NULL,
  price NUMERIC(12, 2) NOT NULL DEFAULT 0,
  washer_id TEXT REFERENCES public.washers(id) ON DELETE SET NULL,
  washer_name TEXT,
  commission NUMERIC(12, 2) DEFAULT 0,
  status TEXT NOT NULL DEFAULT 'espera' CHECK (status IN ('espera', 'lavando', 'listo', 'entregado', 'cancelado')),
  phone TEXT,
  notes TEXT,
  payment_method TEXT,
  estimated_duration INT DEFAULT 30,
  created_at TIMESTAMPTZ DEFAULT NOW(),
  wash_started_at TIMESTAMPTZ,
  ready_at TIMESTAMPTZ,
  delivered_at TIMESTAMPTZ
);

-- 6. TABLA DE GASTOS Y SALIDAS DE CAJA
CREATE TABLE IF NOT EXISTS public.expenses (
  id TEXT PRIMARY KEY DEFAULT uuid_generate_v4()::TEXT,
  category TEXT NOT NULL DEFAULT 'Insumos',
  description TEXT NOT NULL,
  amount NUMERIC(12, 2) NOT NULL DEFAULT 0,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 7. TABLA DE RESERVAS WEB DE CLIENTES
CREATE TABLE IF NOT EXISTS public.customer_bookings (
  id TEXT PRIMARY KEY DEFAULT uuid_generate_v4()::TEXT,
  customer_name TEXT NOT NULL,
  customer_phone TEXT NOT NULL,
  customer_email TEXT,
  plate TEXT NOT NULL,
  vehicle_type TEXT NOT NULL,
  service_name TEXT NOT NULL,
  preferred_date DATE NOT NULL,
  preferred_time TIME NOT NULL,
  status TEXT DEFAULT 'pendiente' CHECK (status IN ('pendiente', 'confirmada', 'cancelada')),
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- ==============================================================================
-- ÍNDICES PARA ALTO RENDIMIENTO
-- ==============================================================================
CREATE INDEX IF NOT EXISTS idx_orders_plate ON public.orders(plate);
CREATE INDEX IF NOT EXISTS idx_orders_status ON public.orders(status);
CREATE INDEX IF NOT EXISTS idx_orders_created_at ON public.orders(created_at DESC);
CREATE INDEX IF NOT EXISTS idx_bookings_phone ON public.customer_bookings(customer_phone);

-- ==============================================================================
-- SEGURIDAD: ROW LEVEL SECURITY (RLS)
-- ==============================================================================
ALTER TABLE public.profiles ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.services ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.washers ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.orders ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.expenses ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.customer_bookings ENABLE ROW LEVEL SECURITY;

-- Políticas de lectura pública (para consulta de estado por placa y reservas)
CREATE POLICY "Lectura pública de servicios activos" ON public.services
  FOR SELECT USING (active = true);

CREATE POLICY "Lectura de estado de orden por placa" ON public.orders
  FOR SELECT USING (true);

CREATE POLICY "Creación de órdenes para personal o clientes" ON public.orders
  FOR INSERT WITH CHECK (true);

CREATE POLICY "Actualización de órdenes" ON public.orders
  FOR UPDATE USING (true);

CREATE POLICY "Lectura pública de lavadores" ON public.washers
  FOR SELECT USING (true);

CREATE POLICY "Gestión completa de gastos para usuarios autorizados" ON public.expenses
  FOR ALL USING (true);

CREATE POLICY "Clientes pueden crear reservas" ON public.customer_bookings
  FOR INSERT WITH CHECK (true);

CREATE POLICY "Lectura de reservas" ON public.customer_bookings
  FOR SELECT USING (true);

